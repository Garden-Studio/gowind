// Command gen writes release.go for a Tailwind CSS release: its version and
// the SHA-256 of each standalone binary, from the sha256sums.txt the release
// publishes.
//
//	go run ./internal/gen v4.3.3
package main

import (
	"bufio"
	"fmt"
	"go/format"
	"net/http"
	"os"
	"regexp"
	"sort"
	"strings"
	"time"
)

var (
	versionPattern = regexp.MustCompile(`^v\d+\.\d+\.\d+$`)
	sumLine        = regexp.MustCompile(`^([0-9a-f]{64})\s+\.?/?(tailwindcss-[a-z0-9.-]+)$`)
)

func main() {
	if len(os.Args) != 2 || !versionPattern.MatchString(os.Args[1]) {
		fmt.Fprintln(os.Stderr, "usage: go run ./internal/gen vX.Y.Z")
		os.Exit(2)
	}
	if err := generate(os.Args[1]); err != nil {
		fmt.Fprintln(os.Stderr, "gen:", err)
		os.Exit(1)
	}
}

func generate(version string) error {
	url := "https://github.com/tailwindlabs/tailwindcss/releases/download/" + version + "/sha256sums.txt"
	client := &http.Client{Timeout: time.Minute}
	response, err := client.Get(url)
	if err != nil {
		return err
	}
	defer response.Body.Close()
	if response.StatusCode != http.StatusOK {
		return fmt.Errorf("%s: HTTP %d", url, response.StatusCode)
	}
	sums := map[string]string{}
	scanner := bufio.NewScanner(response.Body)
	for scanner.Scan() {
		if match := sumLine.FindStringSubmatch(strings.TrimSpace(scanner.Text())); match != nil {
			sums[match[2]] = match[1]
		}
	}
	if err := scanner.Err(); err != nil {
		return err
	}
	if len(sums) == 0 {
		return fmt.Errorf("%s lists no binaries", url)
	}
	assets := make([]string, 0, len(sums))
	for asset := range sums {
		assets = append(assets, asset)
	}
	sort.Strings(assets)
	var source strings.Builder
	source.WriteString("// Code generated by internal/gen from the release's sha256sums.txt; DO NOT EDIT.\n\npackage main\n\n")
	fmt.Fprintf(&source, "// Version is the Tailwind CSS release this module version runs.\nconst Version = %q\n\n", version)
	source.WriteString("// checksums is the SHA-256 of each standalone binary of the release.\nvar checksums = map[string]string{\n")
	for _, asset := range assets {
		fmt.Fprintf(&source, "\t%q: %q,\n", asset, sums[asset])
	}
	source.WriteString("}\n")
	formatted, err := format.Source([]byte(source.String()))
	if err != nil {
		return err
	}
	return os.WriteFile("release.go", formatted, 0o644)
}
